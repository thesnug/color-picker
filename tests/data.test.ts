import { readFileSync } from "node:fs";
import { join } from "node:path";

import { describe, expect, it } from "vitest";

import { buildModules, OUT_DIR } from "../scripts/build-engine-data.js";
import {
  defaultProduct,
  loadAccessibility,
  loadColorNames,
  loadColors,
  loadCombinations,
  loadProduct,
  loadProductEquivalents,
  loadProductIndex,
  loadWadaColors,
} from "../src/data/index.js";
import { storedColors, storedProduct } from "../src/data/store.js";

const ASSETS = join(import.meta.dirname, "..", "assets");
const asset = <T>(path: string): T => JSON.parse(readFileSync(join(ASSETS, path), "utf8")) as T;
const withoutEditorKeys = (value: Record<string, unknown>) =>
  Object.fromEntries(Object.entries(value).filter(([key]) => key !== "$schema" && key !== "$comment"));

describe("data", () => {
  it("loads the vendored Wada colors", () => {
    const colors = loadWadaColors();
    expect(colors).toHaveLength(157);
    expect(colors[0]).toMatchObject({ index: 1, name: "Hermosa Pink", hex: "#ffb3f0" });
  });

  it("bundles exactly the assets, without their editor-only keys", () => {
    expect(loadColors()).toEqual(asset<{ colors: unknown[] }>("derived/colors.json").colors);
    expect(loadCombinations()).toEqual(asset<{ combinations: unknown[] }>("derived/combinations.json").combinations);
    expect(loadAccessibility()).toEqual(withoutEditorKeys(asset("accessibility.json")));
    expect(loadProductIndex()).toEqual(withoutEditorKeys(asset("products/index.json")));
    for (const { id } of loadProductIndex().products) {
      expect(loadProduct(id)).toEqual(withoutEditorKeys(asset(`products/${id}.json`)));
      expect(loadProductEquivalents(id)).toEqual(asset(`products/${id}.equivalents.json`));
    }
    for (const source of ["css", "xkcd"] as const) expect(loadColorNames(source)).toEqual(asset(`names/${source}.json`));
  });

  it("keeps the generated modules in step with the assets", () => {
    for (const module of buildModules()) {
      expect(readFileSync(join(OUT_DIR, module.file), "utf8"), module.file).toContain(
        `// Generated by scripts/build-engine-data.ts from ${module.sources.join(", ")}.`,
      );
    }
  });

  it("hands each caller its own copy", () => {
    const product = loadProduct("comfort-colors-1717");
    product.colors[0]!.name = "Changed";
    expect(loadProduct("comfort-colors-1717").colors[0]!.name).not.toBe("Changed");
    expect(storedProduct("comfort-colors-1717").colors[0]!.name).not.toBe("Changed");
    const colors = loadColors();
    colors.pop();
    expect(storedColors()).toHaveLength(157);
    expect(defaultProduct().id).toBe("comfort-colors-1717");
  });

  it("rejects an unknown product", () => {
    expect(() => loadProduct("gildan-5000")).toThrow('Unknown product "gildan-5000". Known products: comfort-colors-1717.');
    expect(() => loadProductEquivalents("gildan-5000")).toThrow(/Unknown product/);
  });
});
