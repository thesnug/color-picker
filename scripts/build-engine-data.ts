/**
 * Bundle the JSON assets as TypeScript modules, so the core and the engine
 * entry point read their data without `node:fs` or `import.meta.url`, which
 * bundlers and vendored copies cannot follow.
 *
 *   npm run data:build   # also writes src/data/generated/*.ts
 *   npm run data:check   # also exits 1 if they are stale
 *
 * `assets/` stays the source of truth: these modules are derived from it,
 * never edited by hand, and checked for staleness in CI. Editor-only keys
 * (`$schema`, `$comment`) are left out, as the loaders always dropped them.
 * Each constant carries a type annotation, so its `.d.ts` stays one line.
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = join(here, "..");
const ASSETS = join(ROOT, "assets");
export const OUT_DIR = join(ROOT, "src", "data", "generated");

function readJson(path: string): unknown {
  return JSON.parse(readFileSync(join(ASSETS, path), "utf8"));
}

/** Drop the editor-only `$schema` and `$comment` keys. */
function withoutEditorKeys(value: unknown): unknown {
  if (value === null || typeof value !== "object" || Array.isArray(value)) return value;
  return Object.fromEntries(Object.entries(value).filter(([key]) => key !== "$schema" && key !== "$comment"));
}

/**
 * JSON for a TypeScript module: the outer `depth` levels of objects and arrays
 * one entry per line, so a data change shows as a readable diff, and anything
 * deeper on that entry's line.
 */
export function literal(value: unknown, depth: number, indent = ""): string {
  if (depth <= 0 || value === null || typeof value !== "object") return JSON.stringify(value);
  const inner = `${indent}  `;
  if (Array.isArray(value)) {
    if (value.length === 0) return "[]";
    return `[\n${value.map((v) => `${inner}${literal(v, depth - 1, inner)}`).join(",\n")},\n${indent}]`;
  }
  const entries = Object.entries(value);
  if (entries.length === 0) return "{}";
  return `{\n${entries.map(([k, v]) => `${inner}${JSON.stringify(k)}: ${literal(v, depth - 1, inner)}`).join(",\n")},\n${indent}}`;
}

export interface Module {
  file: string;
  sources: string[];
  imports: string[];
  constants: { name: string; type: string; value: unknown; depth: number; doc: string }[];
}

function render(module: Module): string {
  const header = [
    `// Generated by scripts/build-engine-data.ts from ${module.sources.join(", ")}.`,
    "// Do not edit: change the assets and run `npm run data:build`.",
    "",
    `import type { ${module.imports.join(", ")} } from "../types.js";`,
    "",
  ];
  const body = module.constants.map(
    (c) => `/** ${c.doc} */\nexport const ${c.name}: ${c.type} = ${literal(c.value, c.depth)};\n`,
  );
  return `${[...header, body.join("\n")].join("\n")}`;
}

/** Every generated module, from the current assets. */
export function buildModules(): Module[] {
  const index = withoutEditorKeys(readJson("products/index.json")) as { products: { id: string }[] };
  const ids = index.products.map((p) => p.id);
  const products = Object.fromEntries(ids.map((id) => [id, withoutEditorKeys(readJson(`products/${id}.json`))]));
  const equivalents = Object.fromEntries(ids.map((id) => [id, readJson(`products/${id}.equivalents.json`)]));
  const colors = (readJson("derived/colors.json") as { colors: unknown[] }).colors;
  const combinations = (readJson("derived/combinations.json") as { combinations: unknown[] }).combinations;

  return [
    {
      file: "colors.ts",
      sources: ["assets/derived/colors.json"],
      imports: ["DerivedColor"],
      constants: [{ name: "COLORS", type: "readonly DerivedColor[]", value: colors, depth: 1, doc: "The cleaned Wada colors, in index order." }],
    },
    {
      file: "combinations.ts",
      sources: ["assets/derived/combinations.json"],
      imports: ["Combination"],
      constants: [
        { name: "COMBINATIONS", type: "readonly Combination[]", value: combinations, depth: 1, doc: "The book's combinations, by ID." },
      ],
    },
    {
      file: "accessibility.ts",
      sources: ["assets/accessibility.json"],
      imports: ["Accessibility"],
      constants: [
        {
          name: "ACCESSIBILITY",
          type: "Accessibility",
          value: withoutEditorKeys(readJson("accessibility.json")),
          depth: 3,
          doc: "WCAG, APCA, print, and color-vision thresholds.",
        },
      ],
    },
    {
      file: "products.ts",
      sources: ["assets/products/index.json", ...ids.map((id) => `assets/products/${id}.json`)],
      imports: ["Product", "ProductIndex"],
      constants: [
        { name: "PRODUCT_INDEX", type: "ProductIndex", value: index, depth: 2, doc: "The product index and the default product." },
        {
          name: "PRODUCTS",
          type: "Readonly<Record<string, Product>>",
          value: products,
          depth: 3,
          doc: "Every indexed product by ID.",
        },
      ],
    },
    {
      file: "equivalents.ts",
      sources: ids.map((id) => `assets/products/${id}.equivalents.json`),
      imports: ["ProductEquivalentsFile"],
      constants: [
        {
          name: "EQUIVALENTS",
          type: "Readonly<Record<string, ProductEquivalentsFile>>",
          value: equivalents,
          depth: 3,
          doc: "Each indexed product's stored Wada equivalents, by product ID.",
        },
      ],
    },
    {
      file: "names.ts",
      sources: ["assets/names/css.json", "assets/names/xkcd.json"],
      imports: ["ColorNameSource", "ColorNamesFile"],
      constants: [
        {
          name: "COLOR_NAMES",
          type: "Readonly<Record<ColorNameSource, ColorNamesFile>>",
          value: { css: readJson("names/css.json"), xkcd: readJson("names/xkcd.json") },
          depth: 3,
          doc: "The CSS and xkcd color-name dictionaries, with their sources and licenses.",
        },
      ],
    },
  ];
}

export function main(argv: readonly string[]): number {
  const check = argv.includes("--check");
  let stale = 0;
  for (const module of buildModules()) {
    const path = join(OUT_DIR, module.file);
    const next = render(module);
    if (check) {
      let current: string | undefined;
      try {
        current = readFileSync(path, "utf8");
      } catch {
        current = undefined;
      }
      if (current !== next) {
        process.stderr.write(`stale: ${path}\n`);
        stale++;
      }
    } else {
      mkdirSync(OUT_DIR, { recursive: true });
      writeFileSync(path, next);
      process.stdout.write(`wrote ${path}\n`);
    }
  }
  if (check) {
    if (stale > 0) {
      process.stderr.write("Bundled engine data is stale. Run: npm run data:build\n");
      return 1;
    }
    process.stdout.write("Bundled engine data is up to date.\n");
  }
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exitCode = main(process.argv.slice(2));
}
